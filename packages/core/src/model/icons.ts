const KNOWN: ReadonlySet<string> = new Set(BUILTIN_ICONS);

export function isBuiltinIcon(name: string): boolean {
  return KNOWN.has(name);
}

/**
 * The built-in name to show: unknown names and custom icons fall back to
 * the default; `null` means "no own icon".
 */
export function iconName(ref: IconRef | null, fallback: string): string {
  return ref?.type === "builtin" && KNOWN.has(ref.name) ? ref.name : fallback;
}
